export type Pair = readonly [string, string];

/** Returns [primary, secondary] text for the chosen language. */
export function tr(pair: Pair, lang: Lang): { p: string; s: string } {
  return lang === "ta" ? { p: pair[0], s: pair[1] } : { p: pair[1], s: pair[0] };
}

export function fmtDate(iso: string | null | undefined, lang: Lang, withWeekday = true): string {
  if (!iso) return "";
  const d = new Date(iso.length === 10 ? iso + "T00:00:00+05:30" : iso);
  return d.toLocaleDateString(lang === "ta" ? "ta-IN" : "en-IN", { weekday: withWeekday ? "short" : undefined, day: "numeric", month: "short", timeZone: "Asia/Kolkata" });
}
